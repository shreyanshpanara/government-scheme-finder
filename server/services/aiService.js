const Scheme = require('../models/Scheme');

/**
 * AI Assistant Service for Government Scheme Guidance
 * Integrates external LLM (Gemini / OpenAI) if AI_API_KEY is configured,
 * with an intelligent schema-grounded knowledge base fallback.
 */

const DISCLAIMER_TEXT =
  '⚠️ Disclaimer: This guidance is provided by the YojanaSetu Citizen Assistant for informational awareness based on official government guidelines. Beneficiaries must verify their eligibility and submit applications directly through the respective official portal or designated Kendra.';

class AIService {
  /**
   * Process citizen query and generate a comprehensive, grounded response
   * @param {string} query - User question
   * @param {Object} context - Optional user profile and active scheme context
   */
  async generateResponse(query, context = {}) {
    const apiKey = process.env.AI_API_KEY || process.env.GEMINI_API_KEY;

    // Check if external AI API is available
    if (apiKey && apiKey.trim() !== '') {
      try {
        return await this.callExternalLLM(query, context, apiKey);
      } catch (err) {
        console.warn('[AI Service Warning]: External LLM call failed, falling back to grounded knowledge base:', err.message);
      }
    }

    // Fallback: Intelligent Grounded Knowledge Retrieval Engine
    return await this.knowledgeBaseResponse(query, context);
  }

  /**
   * Call Google Gemini API (or OpenAI compatible) if AI_API_KEY is configured
   */
  async callExternalLLM(query, context, apiKey) {
    const relevantSchemes = await Scheme.find({ active: true }).limit(5).select('name code ministry category benefits eligibilityCriteria documentsRequired applicationProcess officialWebsite helpline');

    const systemPrompt = `You are "SetuSaathi", an expert Indian Government Citizen Welfare AI Assistant on the YojanaSetu portal.
Your mission is to help Indian citizens understand government schemes, verify eligibility criteria, prepare required documents, and guide them through step-by-step application procedures.
Always adhere strictly to these rules:
1. Provide accurate, empathetic, and clear guidance in simple language.
2. Clearly list documents required and application steps when relevant.
3. Never hallucinate fake government URLs or non-existent subsidies.
4. Ground your response on available Indian government schemes.
Context schemes from database: ${JSON.stringify(relevantSchemes)}
User profile context: ${JSON.stringify(context.userProfile || 'Guest')}
Current scheme viewed: ${JSON.stringify(context.currentScheme || 'None')}`;

    const response = await fetch(`https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key=${apiKey}`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        contents: [
          {
            role: 'user',
            parts: [{ text: `${systemPrompt}\n\nUser Question: ${query}` }]
          }
        ],
        generationConfig: {
          temperature: 0.3,
          maxOutputTokens: 800
        }
      })
    });

    if (!response.ok) {
      throw new Error(`Gemini API returned status ${response.status}`);
    }

    const data = await response.json();
    const answer = data.candidates?.[0]?.content?.parts?.[0]?.text;
    if (!answer) throw new Error('No response generated by external model');

    return {
      answer,
      source: 'AI_MODEL_POWERED',
      disclaimer: DISCLAIMER_TEXT,
    };
  }

  /**
   * Grounded Knowledge Base Engine (works offline/without API key)
   */
  async knowledgeBaseResponse(query, context) {
    const lowerQuery = query.toLowerCase();
    let targetScheme = null;

    // 1. If user is currently looking at a specific scheme
    if (context.currentSchemeId) {
      targetScheme = await Scheme.findById(context.currentSchemeId);
    }

    // 2. Otherwise detect scheme mentioned in query
    if (!targetScheme) {
      const allSchemes = await Scheme.find({ active: true });
      for (const scheme of allSchemes) {
        const code = scheme.code.toLowerCase();
        const name = scheme.name.toLowerCase();
        if (lowerQuery.includes(code) || lowerQuery.includes(name.split(' ')[0].toLowerCase())) {
          targetScheme = scheme;
          break;
        }
      }
    }

    // Keyword detection
    const isAskingDocuments = lowerQuery.includes('document') || lowerQuery.includes('doc') || lowerQuery.includes('kagaz') || lowerQuery.includes('proof');
    const isAskingEligibility = lowerQuery.includes('eligible') || lowerQuery.includes('criteria') || lowerQuery.includes('who can apply') || lowerQuery.includes('age');
    const isAskingApply = lowerQuery.includes('apply') || lowerQuery.includes('process') || lowerQuery.includes('how to') || lowerQuery.includes('steps');
    const isAskingBenefits = lowerQuery.includes('benefit') || lowerQuery.includes('money') || lowerQuery.includes('amount') || lowerQuery.includes('paisa');

    let answer = '';
    const suggestedSchemes = [];

    if (targetScheme) {
      suggestedSchemes.push({
        id: targetScheme._id,
        name: targetScheme.name,
        code: targetScheme.code,
        website: targetScheme.officialWebsite,
      });

      if (isAskingDocuments) {
        const docs = targetScheme.documentsRequired || targetScheme.documents || [];
        answer = `### 📄 Documents Required for **${targetScheme.name}**\n\nTo apply smoothly, keep the following official documents ready:\n\n` +
          (docs.length > 0
            ? docs.map((doc, idx) => `${idx + 1}. **${doc.name || 'Document'}** ${doc.mandatory ? '*(Mandatory)*' : '*(Optional)*'}: ${doc.description || 'Verification proof'}`).join('\n')
            : '• Standard KYC documentation (Aadhaar, Bank Passbook, Address Proof)') +
          `\n\n📌 **Helpline**: ${targetScheme.helpline || '1800-11-0001'}\n🌐 **Official Portal**: [${targetScheme.officialWebsite}](${targetScheme.officialWebsite})`;
      } else if (isAskingApply) {
        const steps = targetScheme.applicationProcess?.steps || [];
        answer = `### 🚀 How to Apply for **${targetScheme.name}**\n\n**Application Mode**: ${targetScheme.applicationProcess?.mode || 'Online'}\n\n**Step-by-step Process**:\n` +
          (steps.length > 0
            ? steps.map((step, idx) => `${idx + 1}. ${step}`).join('\n')
            : '1. Visit the official scheme portal.\n2. Complete biometric or Aadhaar verification.\n3. Submit application along with required documents.') +
          `\n\n🌐 **Apply directly at**: [${targetScheme.officialWebsite}](${targetScheme.officialWebsite})\n📞 **Citizen Support**: ${targetScheme.helpline || '1800-11-0001'}`;
      } else if (isAskingEligibility) {
        const crit = targetScheme.eligibilityCriteria || {};
        const states = Array.isArray(crit.allowedStates) && crit.allowedStates.length > 0 ? crit.allowedStates.join(', ') : 'All India';
        const occs = Array.isArray(crit.allowedOccupations) && crit.allowedOccupations.length > 0 ? crit.allowedOccupations.join(', ') : 'All';
        answer = `### 🔍 Eligibility Criteria for **${targetScheme.name}**\n\n` +
          `* **Age Group**: ${crit.minAge ?? 0} to ${crit.maxAge ?? 120} years\n` +
          `* **Gender**: ${crit.gender || 'All'}\n` +
          `* **Jurisdiction**: ${states}\n` +
          `* **Income Ceiling**: ${crit.maxAnnualIncome ? `Up to ₹${crit.maxAnnualIncome.toLocaleString('en-IN')}/year` : 'No upper income limit'}\n` +
          `* **Target Occupations**: ${occs}\n` +
          (crit.customRules && crit.customRules.length > 0 ? `* **Special Conditions**: ${crit.customRules.join('; ')}\n` : '') +
          `\n💡 You can click the **Check Eligibility** button on this scheme card to run an instant automated match against your profile!`;
      } else {
        const benefitsList = Array.isArray(targetScheme.benefits) ? targetScheme.benefits : [];
        answer = `### 🇮🇳 About **${targetScheme.name}**\n\n` +
          `**Governing Ministry**: ${targetScheme.ministry}\n\n` +
          `**Key Benefits**: ${targetScheme.benefitAmount || 'Direct Support'}\n\n` +
          `${targetScheme.description}\n\n` +
          (benefitsList.length > 0
            ? `**Highlights**:\n` + benefitsList.map((b) => `• ${b}`).join('\n') + '\n\n'
            : '') +
          `🌐 Official Website: [${targetScheme.officialWebsite}](${targetScheme.officialWebsite})`;
      }
    } else {
      // General question search
      let matchingSchemes = [];
      if (lowerQuery.includes('scholarship') || lowerQuery.includes('student') || lowerQuery.includes('college')) {
        matchingSchemes = await Scheme.find({ category: 'Education & Learning' }).limit(3);
      } else if (lowerQuery.includes('farmer') || lowerQuery.includes('kisan') || lowerQuery.includes('agriculture')) {
        matchingSchemes = await Scheme.find({ category: 'Agriculture & Rural' }).limit(3);
      } else if (lowerQuery.includes('health') || lowerQuery.includes('hospital') || lowerQuery.includes('ayushman')) {
        matchingSchemes = await Scheme.find({ category: 'Health & Wellness' }).limit(3);
      } else if (lowerQuery.includes('business') || lowerQuery.includes('loan') || lowerQuery.includes('mudra')) {
        matchingSchemes = await Scheme.find({ category: { $in: ['Business & MSME', 'Financial Inclusion'] } }).limit(3);
      } else if (lowerQuery.includes('woman') || lowerQuery.includes('girl') || lowerQuery.includes('female')) {
        matchingSchemes = await Scheme.find({ category: 'Women & Child' }).limit(3);
      } else {
        matchingSchemes = await Scheme.find({ featured: true }).limit(3);
      }

      matchingSchemes.forEach((s) => {
        suggestedSchemes.push({
          id: s._id,
          name: s.name,
          code: s.code,
          website: s.officialWebsite,
        });
      });

      answer = `Namaste! I am your **YojanaSetu Citizen Assistant**.\n\nBased on your query, here are the most relevant government welfare programs available in India:\n\n` +
        matchingSchemes
          .map(
            (s, idx) =>
              `${idx + 1}. **${s.name}** (${s.code})\n` +
              `   • **Benefit**: ${s.benefitAmount}\n` +
              `   • **Ministry**: ${s.ministry}\n` +
              `   • **Official Link**: [${s.officialWebsite}](${s.officialWebsite})`
          )
          .join('\n\n') +
        `\n\n💡 You can ask me specific questions like: *"What documents are needed for PM-KISAN?"* or *"How to apply for NSP Scholarship?"*`;
    }

    return {
      answer,
      source: 'KNOWLEDGE_BASE_ASSISTANT',
      suggestedSchemes,
      disclaimer: DISCLAIMER_TEXT,
    };
  }
}

module.exports = new AIService();
